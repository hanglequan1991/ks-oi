// Statement builders for one synced hotel tab (STORY-14, TASK-50).
//
// buildHotelStatements() only builds D1 prepared statements; the caller runs them
// in one db.batch(), so a failed tab rolls back as a whole. Every statement is
// idempotent: running the same input twice leaves the same table contents.

import { foldText } from "../domain/fold";
import type { ParsedHotel } from "./record";
import type { SheetTab } from "./sheetSource";

export type HotelWriteContext = {
	tab: SheetTab;
	record: ParsedHotel;
	/** Stable id from hotelIdFor(fileId, gid). */
	hotelId: string;
	/** Slug generated by the caller; never changed after the hotel row exists. */
	slug: string;
	now: string;
	/** Status of a new hotel: published when true, review when false. */
	autoPublish: boolean;
	/** Status of the hotel before this run; null for a new hotel. Informational: the SQL never changes status. */
	existingStatus: "review" | "published" | "hidden" | null;
	hash: string;
};

/** City slug: the folded file name with spaces turned into dashes. */
function citySlugFor(fileName: string): string {
	return foldText(fileName).replace(/ /g, "-");
}

/** Folded label, the form used to match facility synonyms. */
function foldLabel(label: string): string {
	return foldText(label);
}

/** Distinct, non-empty folded labels in input order. */
function distinctFolded(labels: string[]): string[] {
	const seen = new Set<string>();
	for (const label of labels) {
		const folded = foldLabel(label);
		if (folded !== "") seen.add(folded);
	}
	return [...seen];
}

/** Matches a folded label to a catalog code: by code, or by a folded synonym. */
const MATCH_CATALOG = `(c.code = ? OR EXISTS (SELECT 1 FROM json_each(c.synonyms) j WHERE j.value = ?))`;

/**
 * Statements that write one sheet tab: city, hotel, images and sheet facilities.
 * Nothing is executed here.
 */
export function buildHotelStatements(
	db: D1Database,
	ctx: HotelWriteContext,
): D1PreparedStatement[] {
	const { tab, record, hotelId, slug, now, hash } = ctx;
	const citySlug = citySlugFor(tab.fileName);
	const statements: D1PreparedStatement[] = [];

	// City: the first write wins. name_vi is the file name, verbatim.
	statements.push(
		db
			.prepare(
				"INSERT INTO cities (slug, name_vi) VALUES (?, ?) ON CONFLICT(slug) DO NOTHING",
			)
			.bind(citySlug, tab.fileName),
	);

	// Hotel: status is set only on insert, so an existing row keeps its status.
	// The slug is set only on insert, so it is never changed by a later run.
	const initialStatus = ctx.autoPublish ? "published" : "review";
	statements.push(
		db
			.prepare(
				`INSERT INTO hotels (
           id, slug, city_slug, name, name_search, stars, address, area,
           description_vi, description_en, status,
           source_file_id, source_gid, source_hash, synced_at,
           rooms_synced_at, facilities_synced_at
         ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
         ON CONFLICT(id) DO UPDATE SET
           city_slug = excluded.city_slug,
           name = excluded.name,
           name_search = excluded.name_search,
           stars = excluded.stars,
           address = excluded.address,
           area = excluded.area,
           description_vi = excluded.description_vi,
           description_en = excluded.description_en,
           source_file_id = excluded.source_file_id,
           source_gid = excluded.source_gid,
           source_hash = excluded.source_hash,
           synced_at = excluded.synced_at,
           rooms_synced_at = excluded.rooms_synced_at,
           facilities_synced_at = excluded.facilities_synced_at`,
			)
			.bind(
				hotelId,
				slug,
				citySlug,
				tab.tabName,
				foldText(tab.tabName),
				record.stars,
				record.address,
				record.area,
				record.descriptionVi,
				record.descriptionEn,
				initialStatus,
				tab.fileId,
				tab.gid,
				hash,
				now,
				now,
				now,
			),
	);

	// Images: replace all rows; duplicates dropped, first occurrence keeps its place.
	statements.push(
		db.prepare("DELETE FROM hotel_images WHERE hotel_id = ?").bind(hotelId),
	);
	const urls = [...new Set(record.images)];
	urls.forEach((url, position) => {
		statements.push(
			db
				.prepare(
					"INSERT INTO hotel_images (hotel_id, url, position) VALUES (?, ?, ?)",
				)
				.bind(hotelId, url, position),
		);
	});

	// Facilities: replace only the sheet rows; mytour, hotel_site and override rows stay.
	statements.push(
		db
			.prepare("DELETE FROM hotel_facilities WHERE hotel_id = ? AND source = 'sheet'")
			.bind(hotelId),
	);
	for (const folded of distinctFolded(record.facilities)) {
		statements.push(
			db
				.prepare(
					`INSERT OR IGNORE INTO hotel_facilities (hotel_id, code, source, confirmed)
           SELECT ?, c.code, 'sheet', 1 FROM facility_catalog c WHERE ${MATCH_CATALOG}`,
				)
				.bind(hotelId, folded, folded),
		);
	}

	return statements;
}

/**
 * Labels (verbatim, first occurrence per folded form) that match no catalog code or
 * synonym. The caller reports them; they are not stored.
 */
export async function unmappedFacilities(
	db: D1Database,
	labels: string[],
): Promise<string[]> {
	const unmapped: string[] = [];
	const seen = new Set<string>();
	for (const label of labels) {
		const folded = foldLabel(label);
		if (seen.has(folded)) continue;
		seen.add(folded);
		const hit =
			folded === ""
				? null
				: await db
						.prepare(
							`SELECT 1 AS hit FROM facility_catalog c WHERE ${MATCH_CATALOG} LIMIT 1`,
						)
						.bind(folded, folded)
						.first<{ hit: number }>();
		if (hit === null) unmapped.push(label);
	}
	return unmapped;
}
